// The Go operation table and typed call wrappers (clients/go/b2/ops.gen.go). Models come from oapi-codegen; names
// here follow its conventions (`sessions.resolve_unknown` → `SessionsResolveUnknown`, `worker_id` → `WorkerId`).
import { deref, schemaName } from './spec.mjs';

const HEADER = '// Code generated by tools/codegen from api/b2.openapi.yaml. DO NOT EDIT.';
// Wrappers written by hand in transport.go: Hello also refuses an unknown protocol major.
const HANDWRITTEN = new Set(['hello']);

/** oapi-codegen's type-name form: split on non-alphanumerics, upper-case each part's first letter. */
function goName(name) {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map(part => part[0].toUpperCase() + part.slice(1))
    .join('');
}

/** Go identifier for a path argument: `worker_id` → `workerID`. */
function argName(name) {
  const parts = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
  return parts
    .map((p, i) => (p.toLowerCase() === 'id' ? 'ID' : i === 0 ? p : p[0].toUpperCase() + p.slice(1)))
    .join('');
}

function goType(spec, schema, where) {
  const name = schemaName(schema);
  if (name) {
    const target = deref(spec, schema);
    // A named array (Interactions) is a slice alias in the models; return it by value.
    return target.type === 'array' ? { type: name, pointer: false } : { type: `*${name}`, pointer: true, base: name };
  }
  if (schema.type === 'array' && schemaName(schema.items)) return { type: `[]${schemaName(schema.items)}`, pointer: false };
  throw new Error(`${where}: response schema must be a $ref or an array of $ref`);
}

function queryEncoder(op) {
  const query = op.params.filter(p => p.in === 'query');
  const set = (p, value) => {
    const conv = { string: value, integer: `strconv.Itoa(${value})`, number: `strconv.FormatFloat(${value}, 'g', -1, 64)`, boolean: `strconv.FormatBool(${value})` }[p.kind];
    return `q.Set(${JSON.stringify(p.name)}, ${conv})`;
  };
  const required = query.some(p => p.required);
  const lines = query.map(p => {
    const field = `params.${goName(p.name)}`;
    return p.required ? `\t${set(p, field)}` : `\tif ${field} != nil {\n\t\t${set(p, `*${field}`)}\n\t}`;
  });
  return { required, body: lines.join('\n') };
}

export function goOps(spec, ops, eventInfo, profiles = {}) {
  const table = ops
    .map(op => `\t${'Op' + goName(op.operationId)} = Operation{ID: ${JSON.stringify(op.operationId)}, Method: ${JSON.stringify(op.method)}, Path: ${JSON.stringify(op.path)}, Mutation: ${op.mutation}, Stream: ${op.stream}, Body: ${JSON.stringify(op.bodyMode)}, MediaTypes: []string{${op.mediaTypes.map(t => JSON.stringify(t)).join(', ')}}, MaxBodyBytes: ${op.maxBodyBytes}, Response: ${JSON.stringify(op.responseMode)}, MaxFrameBytes: ${op.maxFrameBytes ?? 0}, MaxResponseBytes: ${op.maxResponseBytes ?? 0}}`)
    .join('\n');
  const profileTable = Object.entries(profiles)
    .map(([name, methods]) => `\t${JSON.stringify(name)}: {\n${methods.map(m => `\t\t${JSON.stringify(m)},`).join('\n')}\n\t},`)
    .join('\n');
  const wrappers = ops
    // SSE (Watch), binary uploads and ndjson or binary responses (streamed bytes, P1-17) are hand-written.
    .filter(op => !op.stream && !op.raw && op.bodyMode !== 'binary' && !HANDWRITTEN.has(op.operationId))
    .map(op => {
      const name = goName(op.operationId);
      const ok = op.responses.find(r => r.status === '200');
      const out = goType(spec, ok.schema, op.operationId);
      const pathParams = op.params.filter(p => p.in === 'path');
      const query = op.params.filter(p => p.in === 'query');
      const args = ['ctx context.Context', ...pathParams.map(p => `${argName(p.name)} string`)];
      let queryArg = 'nil';
      let prelude = '';
      if (query.length) {
        const enc = queryEncoder(op);
        args.push(`params ${enc.required ? '' : '*'}${name}Params`);
        prelude = enc.required
          ? `\tq := url.Values{}\n${enc.body}\n`
          : `\tq := url.Values{}\n\tif params != nil {\n${enc.body.replace(/^/gm, '\t')}\n\t}\n`;
        queryArg = 'q';
      }
      let bodyArg = 'nil';
      if (op.body) {
        const bodyType = schemaName(op.body);
        if (!bodyType) throw new Error(`${op.operationId}: request body must be a $ref`);
        args.push(`body ${bodyType}`);
        bodyArg = 'body';
      }
      const pathArgs = pathParams.length ? `[]string{${pathParams.map(p => argName(p.name)).join(', ')}}` : 'nil';
      const decl = out.pointer ? `\tvar out ${out.base}` : `\tvar out ${out.type}`;
      const ret = out.pointer ? '&out' : 'out';
      const summary = `// ${name} calls ${op.operationId} (${op.method} ${op.path})${op.mutation ? '. A mutation: sent once, never retried' : ''}.`;
      return `${summary}
func (c *Client) ${name}(${args.join(', ')}) (${out.type}, error) {
${prelude}${decl}
\tif err := c.do(ctx, Op${name}, ${pathArgs}, ${queryArg}, ${bodyArg}, &out); err != nil {
\t\treturn ${out.pointer ? 'nil' : 'nil'}, err
\t}
\treturn ${ret}, nil
}`;
    })
    .join('\n\n');
  const wrapped = op => !op.stream && !op.raw && op.bodyMode !== 'binary' && !HANDWRITTEN.has(op.operationId);
  const needsStrconv = ops.some(op => op.params.some(p => p.in === 'query' && p.kind !== 'string') && wrapped(op));
  const needsURL = ops.some(op => op.params.some(p => p.in === 'query') && wrapped(op));
  const imports = ['"context"', needsURL ? '"net/url"' : null, needsStrconv ? '"strconv"' : null].filter(Boolean);
  return `${HEADER}

package b2

import (
${imports.map(i => `\t${i}`).join('\n')}
)

// Operation is one B2 operation from the spec.
type Operation struct {
\tID       string
\tMethod   string
\tPath     string
\tMutation bool
\tStream   bool
\t// Body is x-piw-body: "json", "binary" (streamed, MediaTypes only) or "none".
\tBody       string
\tMediaTypes []string
\t// MaxBodyBytes is the most request body bytes the worker accepts (413 beyond).
\tMaxBodyBytes int64
\t// Response is x-piw-response of the 200 response: "json", "sse", "ndjson" or "binary".
\tResponse string
\t// MaxFrameBytes is, for an sse response, the most bytes one record may carry.
\tMaxFrameBytes int
\t// MaxResponseBytes is, for an ndjson or binary response, the most body bytes a 200 may carry.
\tMaxResponseBytes int64
}

var (
${table}
)

// Operations lists every operation in spec order.
var Operations = []Operation{
${ops.map(op => `\tOp${goName(op.operationId)},`).join('\n')}
}

// EventTypes lists every event type in the x-piw-event manifest, in union order.
var EventTypes = []string{
${eventInfo.members.map(m => `\t${JSON.stringify(m.type)},`).join('\n')}
}

// GrantProfiles maps each grant profile in the spec (info.x-piw-grant-profiles) to its exact method list. A grant
// registered with a profile may call exactly these operations; "bridge" is Shep's worker driver.
var GrantProfiles = map[string][]string{
${profileTable}
}

${wrappers}
`;
}
