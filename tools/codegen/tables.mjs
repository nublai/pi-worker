// The in-repo tables (plan 4.1 step 4): the TS route table and the TS event manifest with per-event publishers.
const HEADER = '// Generated by tools/codegen from api/b2.openapi.yaml. Do not edit.';
const q = JSON.stringify;

export function routeTable(ops, jsonCap) {
  const entry = op => {
    const responses = op.responses
      .map(r => {
        const validate = r.contentType === 'application/json' ? `v.response_${op.key}_${r.status}` : 'null';
        return `      '${r.status}': { contentType: ${q(r.contentType)}, mode: ${q(r.mode)}, maxFrameBytes: ${r.maxFrameBytes ?? 'null'}, validate: ${validate} },`;
      })
      .join('\n');
    const params = op.params.map(p => `{ name: ${q(p.name)}, in: ${q(p.in)}, required: ${p.required}, kind: ${q(p.kind)} }`);
    return [
      `  ${q(op.operationId)}: {`,
      `    operationId: ${q(op.operationId)},`,
      `    method: ${q(op.method)},`,
      `    path: ${q(op.path)},`,
      `    segments: ${q(op.segments)},`,
      `    mutation: ${op.mutation},`,
      `    supported: ${op.supported},`,
      `    grantMethod: ${q(op.operationId)},`,
      `    stream: ${op.stream},`,
      `    body: ${q(op.bodyMode)},`,
      `    mediaTypes: ${q(op.mediaTypes)},`,
      `    maxBodyBytes: ${op.maxBodyBytes},`,
      `    responseMode: ${q(op.responseMode)},`,
      `    params: [${params.join(', ')}],`,
      `    validateParams: v.params_${op.key},`,
      `    validateBody: ${op.body ? `v.request_${op.key}` : 'null'},`,
      `    responses: {`,
      responses,
      `    },`,
      `  },`,
    ].join('\n');
  };
  return `${HEADER}
import * as v from './validators.js';
import type { Validator } from './validators.js';

export type ParamKind = 'string' | 'integer' | 'number' | 'boolean';
export interface ParamSpec {
  readonly name: string;
  readonly in: 'path' | 'query' | 'header';
  readonly required: boolean;
  readonly kind: ParamKind;
}
export type BodyMode = 'json' | 'binary' | 'none';
export type ResponseMode = 'json' | 'sse';
export interface ResponseSpec {
  readonly contentType: 'application/json' | 'text/event-stream';
  /** x-piw-response for a success response; error responses are json. */
  readonly mode: ResponseMode;
  /** x-piw-max-frame-bytes for an sse response: the most bytes one record may carry. */
  readonly maxFrameBytes: number | null;
  readonly validate: Validator | null;
}
export interface Route {
  readonly operationId: string;
  readonly method: 'GET' | 'PUT' | 'POST' | 'DELETE' | 'PATCH';
  readonly path: string;
  /** Path segments; \`{name}\` marks a path parameter. */
  readonly segments: readonly string[];
  /** x-piw-mutation: the body carries command_id; a failure after dispatch is effect unknown. */
  readonly mutation: boolean;
  /** false when the spec marks the operation x-piw-status: unsupported (answers 501 no_effect). */
  readonly supported: boolean;
  /** The method a grant must allow. */
  readonly grantMethod: string;
  /** The 200 response is text/event-stream; frames validate against the event union. */
  readonly stream: boolean;
  /** x-piw-body: how the router reads the request body before any handler. */
  readonly body: BodyMode;
  /** The accepted request media types (empty for none). */
  readonly mediaTypes: readonly string[];
  /** The request body byte limit: JSON cap or x-piw-max-bytes; 0 for none. */
  readonly maxBodyBytes: number;
  /** x-piw-response of the 200 response. */
  readonly responseMode: ResponseMode;
  readonly params: readonly ParamSpec[];
  /** Validates { path, query, header } after scalar conversion. */
  readonly validateParams: Validator;
  readonly validateBody: Validator | null;
  readonly responses: Readonly<Record<string, ResponseSpec>>;
}

/** info.x-piw-json-max-bytes: the JSON request body cap. */
export const jsonBodyLimit = ${jsonCap};

export const routes = {
${ops.map(entry).join('\n')}
} as const satisfies Record<string, Route>;

export type OperationId = keyof typeof routes;
export type SupportedOperationId = {
  [K in OperationId]: (typeof routes)[K]['supported'] extends true ? K : never;
}[OperationId];
export const operationIds = Object.keys(routes) as OperationId[];
`;
}

/** The client's table: no validators (the client has no runtime dependencies), just what a request needs. */
export function clientRouteTable(ops) {
  const entry = op =>
    `  ${q(op.operationId)}: { method: ${q(op.method)}, path: ${q(op.path)}, mutation: ${op.mutation}, stream: ${op.stream}, body: ${q(op.bodyMode)}, mediaTypes: ${q(op.mediaTypes)}, maxBodyBytes: ${op.maxBodyBytes}, responseMode: ${q(op.responseMode)}, maxFrameBytes: ${op.maxFrameBytes ?? 'null'} },`;
  return `${HEADER}
export interface ClientRoute {
  readonly method: 'GET' | 'PUT' | 'POST' | 'DELETE' | 'PATCH';
  /** \`{name}\` marks a path parameter. */
  readonly path: string;
  /** x-piw-mutation: never retried; a failure after the request bytes are written is effect unknown. */
  readonly mutation: boolean;
  readonly stream: boolean;
  /** x-piw-body: json, binary (streamed, the declared media types) or none. */
  readonly body: 'json' | 'binary' | 'none';
  readonly mediaTypes: readonly string[];
  /** The worker refuses a larger body with 413. */
  readonly maxBodyBytes: number;
  /** x-piw-response of the 200 response. */
  readonly responseMode: 'json' | 'sse';
  /** For an sse response, the most bytes one record may carry; a longer record is refused, never truncated. */
  readonly maxFrameBytes: number | null;
}

export const routes = {
${ops.map(entry).join('\n')}
} as const satisfies Record<string, ClientRoute>;

export type OperationId = keyof typeof routes;
`;
}

export function eventTable(eventInfo) {
  const { members, unionName } = eventInfo;
  const published = members.filter(m => m.visibility === 'worker');
  const manifest = members
    .map(m =>
      `  ${q(m.type)}: { schema: ${q(m.name)}, producer: ${q(m.producer)}, durability: ${q(m.durability)}, visibility: ${q(m.visibility)}, validate: v.event_${m.name} },`,
    )
    .join('\n');
  const evidence = m =>
    m.durability === 'journal'
      ? `'supervisor_journal_fsynced' as const`
      : m.durability === 'memory'
        ? `'observed_memory' as const`
        : `input.appended ? ('supervisor_journal_fsynced' as const) : ('observed_memory' as const)`;
  const publisher = m => `    ${q(m.type)}: input => {
      const frame: EventOf<${q(m.type)}> = {
        type: ${q(m.type)},
        ...port.stamp(),
        producer: ${q(m.producer)},
        execution_id: input.execution_id,
        evidence: ${evidence(m)},
        worker_id: input.worker_id,
        data: input.data,
      };
      if (!v.event_${m.name}(frame)) throw new EventSchemaError(${q(m.type)}, v.event_${m.name}.errors ?? []);
      port.deliver(frame);
    },`;
  return `${HEADER}
import * as v from './validators.js';
import type { ValidationError } from './validators.js';
import type { components } from './api.js';

export type EventFrame = components['schemas'][${q(unionName)}];
export type EventType = EventFrame['type'];
export type EventOf<T extends EventType> = Extract<EventFrame, { type: T }>;
export type Cursor = components['schemas']['Cursor'];

/** The x-piw-event manifest. */
export const eventManifest = {
${manifest}
} as const;

export const validateEventFrame = v.event_frame;

/** Proof that a journal record was appended and fsynced. Only the journal creates one. */
export interface JournalAppended {
  readonly fsynced: true;
  readonly label: string;
}

/** Worker-visible events; the hub alone sends supervisor frames (snapshot, overflow). */
export type WorkerEventType = ${published.map(m => q(m.type)).join(' | ')};

type Appended<T extends WorkerEventType> = (typeof eventManifest)[T]['durability'] extends 'journal'
  ? { appended: JournalAppended }
  : (typeof eventManifest)[T]['durability'] extends 'labelled'
    ? { appended?: JournalAppended }
    : { appended?: never };

/** A durable event can only be published with the journal append result that made it durable. */
export type PublishInput<T extends WorkerEventType> = {
  worker_id: string;
  execution_id: EventOf<T>['execution_id'];
  data: EventOf<T>['data'];
} & Appended<T>;

/** The hub side: assigns the transport cursor and event id, then fans the frame out to subscribers. */
export interface EventPort {
  stamp(): { cursor: Cursor; event_id: string };
  deliver(frame: EventFrame): void;
}

export class EventSchemaError extends Error {
  constructor(
    readonly eventType: string,
    readonly errors: readonly ValidationError[],
  ) {
    super(\`event \${eventType} does not match its schema\`);
  }
}

/** One typed publisher per worker-visible event; each frame is validated before delivery. */
export function createPublishers(port: EventPort): { readonly [T in WorkerEventType]: (input: PublishInput<T>) => void } {
  return {
${published.map(publisher).join('\n')}
  };
}
`;
}
