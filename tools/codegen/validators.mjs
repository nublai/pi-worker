// Ajv 2020 standalone validators for every request body, parameter set, JSON response and event (plan 4.1 step 3).
// Generated code needs no runtime package: Ajv's one runtime helper (code-point string length) is inlined, and
// any other runtime `require` fails generation so a new dependency is never added silently.
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Each named schema is its own top-level Ajv schema, so it compiles to one shared function. Ids are never fetched.
const schemaId = name => `urn:piw:schema:${name}`;

/** Rewrites `#/components/schemas/X` to the top-level id of X throughout a schema. */
function rewriteRefs(node) {
  if (Array.isArray(node)) return node.map(rewriteRefs);
  if (!node || typeof node !== 'object') return node;
  return Object.fromEntries(
    Object.entries(node).map(([k, v]) => [
      k,
      k === '$ref' && typeof v === 'string' && v.startsWith('#/components/schemas/')
        ? schemaId(v.slice('#/components/schemas/'.length))
        : rewriteRefs(v),
    ]),
  );
}

function extensionKeywords(node, found = new Set()) {
  if (Array.isArray(node)) node.forEach(n => extensionKeywords(n, found));
  else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith('x-')) found.add(k);
      extensionKeywords(v, found);
    }
  }
  return found;
}

function paramsSchema(spec, op) {
  const group = (where, extra) => {
    const list = op.params.filter(p => p.in === where);
    const key = p => (where === 'header' ? p.name.toLowerCase() : p.name);
    return {
      type: 'object',
      additionalProperties: extra,
      required: list.filter(p => p.required).map(key),
      properties: Object.fromEntries(list.map(p => [key(p), rewriteRefs(p.schema)])),
    };
  };
  // Unknown path or query parameters are refused; other headers (authorization, content-type) pass through.
  return {
    type: 'object',
    additionalProperties: false,
    required: ['path', 'query', 'header'],
    properties: { path: group('path', false), query: group('query', false), header: group('header', true) },
  };
}

const UCS2 = /require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g;
const UCS2_INLINE =
  '(function ucs2length(str) { let length = 0; for (const _ of str) length++; return length; })';

export function generateValidators(spec, ops, eventInfo) {
  const ajv = new Ajv2020({
    code: { source: true, esm: true, lines: true },
    strict: true,
    allowUnionTypes: true,
    // Named schemas stay shared functions instead of being inlined into every validator that uses them.
    inlineRefs: false,
  });
  for (const keyword of extensionKeywords(spec.components.schemas)) ajv.addKeyword({ keyword });
  for (const [name, schema] of Object.entries(spec.components.schemas)) ajv.addSchema({ $id: schemaId(name), ...rewriteRefs(schema) });

  const exports = {};
  // Every export gets its own wrapper schema, even when it is just a $ref. Ajv's standalone output dedupes shared
  // functions by name object, and an export that is itself a shared schema would otherwise be emitted twice.
  const add = (name, schema) => {
    const id = `urn:piw:validator:${name}`;
    ajv.addSchema({ $id: id, ...rewriteRefs(schema) });
    exports[name] = id;
  };
  for (const op of ops) {
    add(`params_${op.key}`, paramsSchema(spec, op));
    if (op.body) add(`request_${op.key}`, op.body);
    for (const r of op.responses) {
      if (r.contentType === 'application/json') add(`response_${op.key}_${r.status}`, r.schema);
      // ndjson and binary responses: their headers, by lower-case name, as typed values.
      if (r.headers) add(`response_headers_${op.key}_${r.status}`, r.headers);
    }
  }
  for (const m of eventInfo.members) add(`event_${m.name}`, { $ref: `#/components/schemas/${m.name}` });
  add('event_frame', { $ref: `#/components/schemas/${eventInfo.unionName}` });
  // Router-level refusals (unknown path, wrong method) belong to no operation but still carry Error.
  add('error', { $ref: '#/components/schemas/Error' });

  let js = standaloneCode(ajv, exports).replace(UCS2, UCS2_INLINE);
  if (/\brequire\(/.test(js)) throw new Error('standalone validators need a runtime require; inline it or add the dependency deliberately');
  js = `// Generated by tools/codegen from api/b2.openapi.yaml. Do not edit.\n${js}\n`;

  const names = Object.keys(exports).sort();
  const dts = [
    '// Generated by tools/codegen from api/b2.openapi.yaml. Do not edit.',
    'export interface ValidationError {',
    '  instancePath: string;',
    '  schemaPath: string;',
    '  keyword: string;',
    '  params: Record<string, unknown>;',
    '  message?: string;',
    '}',
    'export interface Validator {',
    '  (data: unknown): boolean;',
    '  errors?: ValidationError[] | null;',
    '}',
    ...names.map(n => `export declare const ${n}: Validator;`),
    '',
  ].join('\n');
  return { js, dts, names };
}
